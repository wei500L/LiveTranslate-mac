_BUILTIN_TABLES = {
    SELECTION_LINEAR_ALGEBRA: LINEAR_ALGEBRA,
    SELECTION_DISCRETE_MATH: DISCRETE_MATH,
}


def builtin_glossary_text(selection: str | None) -> str:
    """Return the built-in glossary text for a settings selection."""
    if selection == SELECTION_BOTH:
        return "\n".join(
            part.rstrip("\n") for part in _BUILTIN_TABLES.values()
        )
    return _BUILTIN_TABLES.get(selection or "", "")


def merged_glossary_text(selection: str | None, user_text: str | None) -> str:
    """Concatenate built-in and user glossary text, user entries last.

    ``terminology.parse_glossary`` keeps the last duplicate for a
    normalized original, so this ordering is what makes a user entry
    override the built-in one on the same term.
    """
    builtin = builtin_glossary_text(selection).strip()
    user = (user_text or "").strip()
    if not builtin:
        return user
    if not user:
        return builtin
    return f"{builtin}\n{user}"
