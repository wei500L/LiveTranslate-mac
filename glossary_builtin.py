"""Built-in course glossaries for the Soniox subtitle highlighter.

These tables exist so a Russian-taught lecture works out of the box: the
user picks a course here instead of typing a hundred terms by hand.  They
are plain ``original => translation`` text consumed by
``terminology.parse_glossary`` — no parser of their own, so they can never
drift from the user-entry format.

Two rules shape every line:

* Russian is inflected and matching is literal, so each term ships its
  nominative plus the oblique cases actually heard in a lecture (``матрица``
  alone would never match ``матрицы``/``матрицу``).  ``ё`` is folded to ``е``
  by ``terminology.normalize_term``, so either spelling matches.
* Chinese translations are at least two characters wherever a standard
  two-character rendering exists (``基底`` not ``基``, ``维数`` not ``维``),
  because a lone CJK character has no word boundary and would highlight
  inside unrelated words.  The handful of terms whose only standard
  translation is a single character (``图``, ``树``, ``秩``...) are kept in
  ``SINGLE_CHAR_TRANSLATIONS``: the CJK length rule keeps them inert on the
  translation line, so only the Russian side highlights and the hover title
  still shows the pairing.

The tables are merged with the user's own ``soniox_glossary`` entries by
``merged_glossary_text`` — user entries win on the same normalized original
(parse order: built-in first, user last).  The built-in text is never
persisted to ``user_settings.json`` and never pre-filled into the panel's
text box: a value written there once is frozen at that build forever (the
same trap ``migrate_style`` guards against).
"""

